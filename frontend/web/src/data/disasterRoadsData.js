// Simple deterministic pseudo-random based on seed
function seededRand(seed) {
  const x = Math.sin(seed) * 10000;
  return x - Math.floor(x);
}

const generateDistrictData = (districtName, year, idx, hasDisaster = false) => {
  const seed = districtName.length * 13 + year * 7 + idx * 31;
  const disasterTypes = ['fire', 'frost'];
  const type = disasterTypes[Math.floor(seededRand(seed + 1) * 2)];
  const day = Math.floor(seededRand(seed + 2) * 28) + 1;
  const month = Math.floor(seededRand(seed + 3) * 12) + 1;

  return {
    name: districtName,
    marker: hasDisaster
      ? {
          type,
          date: `${day}.${month < 10 ? '0' + month : month}.${year}`,
          description: `Катаклизм в ${districtName} в ${year} году. Подробное описание события.`,
        }
      : null,
    allRoads: Math.floor(seededRand(seed + 4) * 500) + 50,
    pavedRoads: Math.floor(seededRand(seed + 5) * 350) + 30,
    otherRoads: Math.floor(seededRand(seed + 6) * 150) + 10,
    nonStandardShare: Math.floor(seededRand(seed + 7) * 30) + 5,
  };
};

